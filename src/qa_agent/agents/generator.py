"""Generator agent (Day 3-4): strategy -> executable pytest + Playwright code.

Renders one parametrized pytest file from the Planner strategy.
Generated files are deterministic: same strategy in, same file out.
Only saved once the file at least collects (see Executor dry-run).
"""

from __future__ import annotations

from pathlib import Path

HEADER = '''"""Generated by qa-agent Generator — do not hand-edit.

Source strategy: Planner.plan() over cases/saucedemo-login.yaml.
Regenerate with: python -m qa_agent.graph --case cases/saucedemo-login.yaml
"""
import pytest
from playwright.sync_api import Page, expect

'''

TEMPLATE = """TARGET_URL = {target_url!r}


@pytest.mark.smoke
@pytest.mark.parametrize(
    "username,password,expected_url,expected_error",
    {cases!r},
    ids={ids!r},
)
def test_login_cases(page: Page, username, password, expected_url, expected_error):
    page.goto(TARGET_URL)
    page.locator('[data-test="username"]').fill(username)
    page.locator('[data-test="password"]').fill(password)
    page.locator('[data-test="login-button"]').click()
    if expected_error is not None:
        expect(page.locator('[data-test="error"]')).to_have_text(expected_error)
        return
    expect(page).to_have_url(expected_url)
    expect(page.locator(".title")).to_have_text("Products")
    expect(page.locator(".inventory_item").first).to_be_visible()
"""


def render_login_tests(strategy: dict) -> str:
    """Render the parametrized login test file for a strategy."""
    cases = [
        (
            c["username"],
            c["password"],
            c["expected_url"],
            c["expected_error"],
        )
        for c in strategy["classes"]
    ]
    ids = [c["id"] for c in strategy["classes"]]
    return HEADER + TEMPLATE.format(
        target_url=strategy["target_url"],
        cases=cases,
        ids=ids,
    )


def generate(strategy: dict, out_path: str | Path) -> Path:
    """Write the rendered test file and return its path."""
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_login_tests(strategy), encoding="utf-8")
    return out
