# the-internet: failed logins stay on /login with a #flash error;
# a success lands on /secure with a #flash success message. Both are
# asserted with to_contain_text because #flash text includes the "×"
# close button after the message.
TEMPLATE_THE_INTERNET = """TARGET_URL = {target_url!r}
SUCCESS_FLASH = {success_flash!r}


@pytest.mark.smoke
@pytest.mark.parametrize(
    "username,password,expected_url,expected_error",
    {cases!r},
    ids={ids!r},
)
def test_login_cases(page: Page, username, password, expected_url, expected_error):
    page.goto(TARGET_URL)
    page.locator('#username').fill(username)
    page.locator('#password').fill(password)
    page.locator('button[type=submit]').click()
    if expected_error is not None:
        expect(page.locator('#flash')).to_contain_text(expected_error)
        expect(page).to_have_url(TARGET_URL)
        return
    expect(page).to_have_url(expected_url)
    expect(page.locator('#flash')).to_contain_text(SUCCESS_FLASH)
"""


def render_login_tests(strategy: dict) -> str:
    """Render the parametrized login test file for a strategy."""
    cases = [
        (
            c["username"],
            c["password"],
            c["expected_url"],
            c["expected_error"],
        )
        for c in strategy["classes"]
    ]
    ids = [c["id"] for c in strategy["classes"]]
    if strategy.get("site") == "the-internet":
        return HEADER_THE_INTERNET + TEMPLATE_THE_INTERNET.format(
            target_url=strategy["target_url"],
            success_flash=strategy["success_flash"],
            cases=cases,
            ids=ids,
        )
    return HEADER + TEMPLATE.format(
        target_url=strategy["target_url"],
        cases=cases,
        ids=ids,
    )


def generate(strategy: dict, out_path: str | Path) -> Path:
    """Write the rendered test file and return its path."""
    out = Path(out_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_login_tests(strategy), encoding="utf-8")
    return out
