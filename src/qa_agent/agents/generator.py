"""Generator agent (Day 3-4): strategy -> executable pytest + Playwright code.

Renders one parametrized pytest file from the Planner strategy.
Generated files are deterministic: same strategy in, same file out.
Only saved once the file at least collects (see Executor dry-run).

Day 13-14: rendering is site-aware. The SauceDemo template is kept
byte-for-byte (its exact-error assertions still apply there); the
the-internet template uses #id locators, button[type=submit], and
to_contain_text on #flash — the flash bar appends a "×" close button
to the message, so an exact to_have_text would fail on a correct login.
"""

from __future__ import annotations

from pathlib import Path

